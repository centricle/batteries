// Build the Netlify _redirects file from the data, so every old URL and every
// alias code reaches its canonical page:
//   1. v1 URLs (legacy_paths)                /traditional/aa  -> /aa
//   2. v1 category roots and their leftovers /camera/*        -> /photo
//   3. every code and alias that is a free, unambiguous slug  /377 -> /sr626sw
// Reserved: anything the build actually emitted at the top level, so a
// redirect can never shadow a real page.
import fs from 'node:fs';
import path from 'node:path';
import { batterySchema } from '../src/lib/schema.mjs';

const slugify = (s) => s.toLowerCase().replace(/\//g, '-').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export function buildRedirects(root, distDir) {
  const dir = path.join(root, 'data/batteries');
  const bs = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .map((f) => batterySchema.parse(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))));
  const reserved = new Set(fs.readdirSync(distDir).map((f) => f.replace(/\.(html|xml|txt|json|svg|webp|png|ico)$/, '')));
  const ids = new Set(bs.map((b) => b.id));
  const lines = ['# Generated by scripts/redirects.mjs at build. Do not edit.'];

  lines.push('', '# v1 battery URLs');
  for (const b of bs) for (const p of b.legacy_paths ?? []) lines.push(`${p}  /${b.id}  301`);

  lines.push('', '# v1 category roots');
  const cats = [
    ['/traditional', '/household'],
    ['/camera', '/photo'],
    ['/search.html', '/search'],
  ];
  for (const [from, to] of cats) lines.push(`${from}  ${to}  301`, `${from}/*  ${to}  301`);
  for (const c of ['button-cells', 'lithium-ion', 'hearing-aid']) lines.push(`/${c}/*  /${c}  301`);

  lines.push('', '# Codes and aliases');
  const owner = new Map();
  for (const b of bs) {
    for (const n of [b.name, ...b.aliases, ...b.codes.map((c) => c.code)]) {
      const s = slugify(n);
      if (!s || s === b.id || ids.has(s) || reserved.has(s)) continue;
      owner.set(s, owner.has(s) && owner.get(s) !== b.id ? null : b.id);
    }
  }
  let n = 0;
  for (const [s, id] of [...owner].sort()) {
    if (!id) continue;
    lines.push(`/${s}  /${id}  301`);
    n++;
  }
  fs.writeFileSync(path.join(distDir, '_redirects'), lines.join('\n') + '\n');
  return n;
}
